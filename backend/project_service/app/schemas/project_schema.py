# Response DTOs — what the server sends TO the client
# ══════════════════════════════════════════════════════════════════════════════

class ProjectResponse(BaseModel):
    """
    DTO for single-item responses — GET /projects/{id}, POST /projects, PATCH /projects/{id}.

    Why this schema exists:
        The client needs to see ALL fields including the generated ones:
            - id (so they can reference this project in future requests)
            - created_at (for display and sorting)
            - updated_at (for display and caching)

        This is the full representation of a project.

    model_config from_attributes=True:
        Tells Pydantic to read data from object attributes, not dict keys.

        Without it:
            project_orm = db.query(Project).first()
            ProjectResponse(**project_orm)  # TypeError — Project is not a dict

        With it:
            project_orm = db.query(Project).first()
            ProjectResponse.model_validate(project_orm)  # Works — reads .id, .name, etc.

        This is how you convert an ORM model to a Pydantic schema.
    """

    id: UUID
    name: str
    owner: str
    status: ProjectStatus
    created_at: datetime
    updated_at: datetime

    model_config = {"from_attributes": True}


class ProjectSummary(BaseModel):
    """
    DTO for list responses — GET /projects (paginated list).

    Why this schema exists:
        When returning 100 projects, including created_at and updated_at
        for every item adds unnecessary payload size.

        For a list view, the client only needs:
            - id (to link to the detail page)
            - name (to display)
            - owner (to display)
            - status (to display)

        When the user clicks a project to view details, the frontend
        makes a second request to GET /projects/{id} which returns
        the full ProjectResponse with timestamps.

    This is a performance optimization — smaller payloads = faster responses.
    """

    id: UUID
    name: str
    owner: str
    status: ProjectStatus

    model_config = {"from_attributes": True}


