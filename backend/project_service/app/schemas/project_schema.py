"""
Without validation:

    POST /projects
    {
        "name": "",
        "owner": "alice"
    }
    → Creates a project with an empty name. Breaks the UI.

    POST /projects
    {
        "name": "   ",
        "owner": "alice"
    }
    → Creates a project with a whitespace-only name. Breaks search.

    POST /projects
    {
        "name": "Project\x00Name",
        "owner": "alice"
    }
    → Null byte in the name. Breaks C-based log parsers and file systems.

    POST /projects
    {
        "name": "Valid Project",
        "owner": "alice",
        "id": "00000000-0000-0000-0000-000000000001",
        "created_at": "2000-01-01T00:00:00Z"
    }
    → Over-posting attack. Client tries to set database-generated fields.

    PATCH /projects/abc123
    {
        "name": ""
    }
    → Updates the project to have an empty name. Data corruption.


With validation:

    All of the above requests are rejected with HTTP 422 and a clear error message:
        "Validation failed: name: ensure this value has at least 1 characters"
        "Validation failed: name: Project name cannot contain null bytes"
        "Extra inputs are not permitted: id, created_at"

    The database never sees invalid data.
    The service layer never sees invalid data.
    Only the validation layer (Pydantic) sees and rejects it.
"""
